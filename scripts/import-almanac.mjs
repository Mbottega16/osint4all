// Turn Almanac's library into extra panels for the board: one panel per subject, one link per site.
// Writes data/almanac.js and adds any missing favicons to icons/ (so the page still makes no network calls).
//
// Usage: node scripts/import-almanac.mjs <path to Almanac's backend/seed/almanac-seed.json>
//   Mac: ~/Desktop/my-brain/projects/almanac/app/backend/seed/almanac-seed.json
//   PC:  ~/OneDrive/Desktop/Almanac/backend/seed/almanac-seed.json
//
// A site is a web host (www. removed). It goes in the panel of the subject most of its resources share.
// A site whose every resource is marked unreachable is left out. The link goes to the site's front page.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/import-almanac.mjs <almanac-seed.json>");
  process.exit(1);
}
const rows = JSON.parse(fs.readFileSync(file, "utf8"));

const sites = new Map();
for (const r of rows) {
  const u = new URL(r.link);
  const host = u.hostname.toLowerCase().replace(/^www\./, "");
  if (!sites.has(host)) sites.set(host, { host, origin: u.origin + "/", names: new Map(), subjects: new Map(), live: 0 });
  const s = sites.get(host);
  s.names.set(r.source_site, (s.names.get(r.source_site) || 0) + 1);
  s.subjects.set(r.subject, (s.subjects.get(r.subject) || 0) + 1);
  if (r.link_status !== "unreachable") s.live++;
}
const top = (m) => [...m].sort((a, b) => b[1] - a[1])[0][0];

const bySubject = new Map();
let left = 0;
for (const s of sites.values()) {
  if (!s.live) { left++; continue; }
  const subject = top(s.subjects).toUpperCase();
  const title = top(s.names) || s.host;
  if (!bySubject.has(subject)) bySubject.set(subject, []);
  bySubject.get(subject).push({ title, url: s.origin, host: s.host });
}

// Favicons: keep one file per host, named after it, like the rest of icons/.
const iconDir = path.join(ROOT, "icons");
const have = new Set(fs.readdirSync(iconDir));
const find = (host) => [...have].find((f) => f.startsWith(host + "."));
async function fetchIcon(host) {
  const url = `https://t3.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=${encodeURIComponent("https://" + host)}&size=32`;
  try {
    const res = await fetch(url);
    if (!res.ok) return "";
    const ext = { "image/png": "png", "image/x-icon": "ico", "image/webp": "webp", "image/svg+xml": "svg" }[(res.headers.get("content-type") || "").split(";")[0]];
    if (!ext) return "";
    const name = `${host}.${ext}`;
    fs.writeFileSync(path.join(iconDir, name), Buffer.from(await res.arrayBuffer()));
    have.add(name);
    return name;
  } catch (e) { return ""; }
}

// Several hosts can share one source name. Those get the host added so they can be told apart.
const nameCount = new Map();
for (const list of bySubject.values()) for (const s of list) nameCount.set(s.title, (nameCount.get(s.title) || 0) + 1);
for (const list of bySubject.values()) for (const s of list) if (nameCount.get(s.title) > 1) s.title += ` (${s.host})`;

const panels = [];
let missing = 0;
for (const [subject, list] of [...bySubject].sort((a, b) => a[0].localeCompare(b[0]))) {
  list.sort((a, b) => a.title.localeCompare(b.title, "en", { sensitivity: "base" }));
  const links = [];
  for (const s of list) {
    let icon = find(s.host) || (await fetchIcon(s.host));
    if (!icon) missing++;
    links.push({ title: s.title, url: s.url, icon });
  }
  panels.push({ title: "ALMANAC · " + subject, links });
}

const out = [
  "// Teaching sites from the owner's Almanac library: one panel per subject. These are NOT part of the OSINT4ALL original.",
  "// Generated by scripts/import-almanac.mjs; hand edits are fine. test/board.test.mjs checks this file.",
  "window.ALMANAC = {",
  `"snapshot": "${new Date().toISOString().slice(0, 10)}",`,
  `"panels": [`,
  panels.map((p) => `{"title": ${JSON.stringify(p.title)}, "links": [\n` + p.links.map((l) => "  " + JSON.stringify(l)).join(",\n") + "\n]}").join(",\n"),
  "]",
  "};",
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "data", "almanac.js"), out);
const n = panels.reduce((t, p) => t + p.links.length, 0);
console.log(`${n} sites in ${panels.length} panels (${left} left out as unreachable, ${missing} without a favicon)`);

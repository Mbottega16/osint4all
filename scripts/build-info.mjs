// Build data/info.js: what the preview panel and the link marks show for each link.
//
// Inputs (all optional except the board itself):
//   data/link-status.json  written by check-links.mjs: status, final address, and each page's own title and description
//   the Atlas seed         the owner's own description, "good for" line, tags and category for sites in the Atlas library
//   data/summaries.json    one-line summaries a local model wrote from a site's own text: { "<url>": "..." }
// Summary order: Atlas's description, then a local-model summary, then the page's own description, then its title.
//
// Usage: node scripts/build-info.mjs [--atlas <atlas-seed.json>]

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const atlasArg = argv.includes("--atlas") ? argv[argv.indexOf("--atlas") + 1] : null;
const home = os.homedir();
const atlasFile = atlasArg || [
  path.resolve(ROOT, "..", "..", "..", "projects", "atlas", "app", "backend", "seed", "atlas-seed.json"),
  path.join(home, "OneDrive", "Desktop", "Atlas", "backend", "seed", "atlas-seed.json"),
].find((p) => fs.existsSync(p));

function loadData(file, name) {
  const src = fs.readFileSync(path.join(ROOT, "data", file), "utf8");
  const p = `window.${name} = `;
  return JSON.parse(src.slice(src.indexOf(p) + p.length, src.lastIndexOf(";")));
}
const readIf = (f) => (fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : null);
const norm = (u) => { try { const x = new URL(u); return x.hostname.replace(/^www\./, "").toLowerCase() + x.pathname.replace(/\/+$/, ""); } catch { return u; } };
const cut = (s, n) => { const t = String(s || "").replace(/\s+/g, " ").trim(); return t.length > n ? t.slice(0, n - 1).trimEnd() + "..." : t; };

const BOARD = loadData("board.js", "BOARD");
const EXTRA = loadData("extra.js", "EXTRA");
const urls = [...new Set([
  ...BOARD.columns.flat().flatMap((p) => p.links.map((l) => l.url)),
  ...EXTRA.groups.flatMap((g) => g.columns.flat().flatMap((p) => p.links.map((l) => l.url))),
])];

const status = (readIf(path.join(ROOT, "data", "link-status.json")) || { links: {} }).links;
const summaries = readIf(path.join(ROOT, "data", "summaries.json")) || {};
const atlas = new Map();
if (atlasFile) for (const e of readIf(atlasFile) || []) atlas.set(norm(e.link), e);
else console.error("No Atlas seed found: Atlas descriptions are skipped (pass --atlas <file>).");

const info = {};
const tally = { atlas: 0, qwen: 0, page: 0, title: 0, none: 0 };
for (const url of urls) {
  const st = status[url] || {};
  const a = atlas.get(norm(url));
  const o = {};
  if (st.s) {
    o.st = st.s;
    if (st.d) o.d = st.d;
    if (st.f) o.f = st.f;
    if (st.c && (st.s === "dead" || st.s === "blocked")) o.cd = st.c;
    if (st.e && st.s === "unreachable") o.er = st.e;
    if (st.u && (st.s === "moved" || st.s === "bounced")) o.fu = st.u;
  }
  let s = "", ss = "";
  if (a && a.description) { s = cut(a.description, 300); ss = "atlas"; }
  else if (summaries[url]) { s = cut(summaries[url], 300); ss = "qwen"; }
  else if (st.m) { s = cut(st.m, 300); ss = "page"; }
  else if (st.t) { s = cut(st.t, 200); ss = "title"; }
  if (s) { o.s = s; o.ss = ss; tally[ss]++; } else tally.none++;
  if (a) {
    if (a.use_case) o.u = cut(a.use_case, 200);
    if (Array.isArray(a.tags) && a.tags.length) o.t = a.tags.slice(0, 6);
    if (a.category) o.c = a.category;
    if (a.warning) o.w = cut(a.warning, 240);
  }
  if (Object.keys(o).length) info[url] = o;
}

const out = [
  "// What the preview panel and link marks show for each link: summary (s, from ss), status (st), and Atlas details.",
  "// Generated by scripts/build-info.mjs from data/link-status.json, the Atlas seed and data/summaries.json.",
  "window.INFO = {",
  Object.entries(info).map(([u, o]) => JSON.stringify(u) + ": " + JSON.stringify(o)).join(",\n"),
  "};",
  "",
].join("\n");
fs.writeFileSync(path.join(ROOT, "data", "info.js"), out);

const counts = {};
for (const o of Object.values(info)) if (o.st) counts[o.st] = (counts[o.st] || 0) + 1;
console.log(`info for ${Object.keys(info).length} of ${urls.length} links · summaries: ${JSON.stringify(tally)} · status: ${JSON.stringify(counts)} · info.js ${(out.length / 1024).toFixed(0)} KB`);
